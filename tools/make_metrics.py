"""Writes senai_remover/_metrics.py: widths for the standard PDF fonts.

    python tools/make_metrics.py

The repairs in senai_remover/repair.py draw text with four of the standard
fonts every PDF viewer has (Times-Roman, Helvetica, Helvetica-Bold and
Symbol) and need their glyph widths to lay it out. The widths come from
Adobe's Core 14 AFM files, as bundled with pypdf 6.
"""

from pathlib import Path

from pypdf._codecs import _symbol_encoding
from pypdf._codecs.core_font_metrics import CORE_FONT_METRICS

OUT = Path(__file__).resolve().parent.parent / "senai_remover" / "_metrics.py"
TEXT_FONTS = ("Times-Roman", "Times-Bold", "Helvetica", "Helvetica-Bold")

HEADER = '''"""Glyph widths of the standard PDF fonts. Generated by tools/make_metrics.py.

Widths are in thousandths of an em. ``WIDTHS[font]`` lists codes 32 to 255
of WinAnsiEncoding (Windows-1252), 0 where the font has no glyph. ``SYMBOL``
maps characters to (code, width) in the Symbol font's own encoding.

The figures are taken from Adobe's Core 14 AFM files, whose notice follows.
They have been reduced to the widths above.

Core 14 AFM Files - ReadMe

This file and the 14 PostScript(R) AFM files it accompanies may be used,
copied, and distributed for any purpose and without charge, with or without
modification, provided that all copyright notices are retained; that the AFM
files are not distributed without this file; that all modifications to this
file or any of the AFM files are prominently noted in the modified file(s);
and that this paragraph is not modified. Adobe Systems has no responsibility
or obligation to support the use of the AFM files.

Copyright (c) 1985, 1987, 1989, 1990, 1991, 1992, 1993, 1997 Adobe Systems
Incorporated. All Rights Reserved.
"""
'''


def winansi(code: int) -> str:
    try:
        return bytes([code]).decode("cp1252")
    except UnicodeDecodeError:
        return ""


def main() -> None:
    lines = [HEADER, "WIDTHS = {"]
    for font in TEXT_FONTS:
        widths = CORE_FONT_METRICS[font].character_widths
        row = [int(widths.get(winansi(code), 0)) if winansi(code) else 0 for code in range(32, 256)]
        lines.append(f'    "{font}": (')
        for start in range(0, len(row), 16):
            lines.append("        " + ", ".join(str(w) for w in row[start:start + 16]) + ",")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    symbol = CORE_FONT_METRICS["Symbol"].character_widths
    lines.append("SYMBOL = {")
    for code, char in enumerate(_symbol_encoding):
        if code >= 32 and char and char in symbol and not char.isascii():
            lines.append(f"    {char!r}: ({code}, {int(symbol[char])}),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
